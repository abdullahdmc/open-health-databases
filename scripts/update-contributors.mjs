// Adds every new GitHub contributor to contributors.json and regenerates
// CITATION.cff. Runs in the "contributors" GitHub Action after each push to
// main; existing entries are never changed, so people can edit their own
// citation name by hand. With no GITHUB_TOKEN it only regenerates CITATION.cff.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const file = join(root, "contributors.json");
const people = JSON.parse(readFileSync(file, "utf8"));

const token = process.env.GITHUB_TOKEN;
const repo = process.env.GITHUB_REPOSITORY || "abdullahdmc/open-health-databases";

async function gh(path) {
  const res = await fetch(`https://api.github.com/${path}`, {
    headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json", "User-Agent": "open-health-databases" },
  });
  if (!res.ok) throw new Error(`GitHub API ${path}: ${res.status}`);
  return res.json();
}

// "John A. Doe" -> { given: "John A.", family: "Doe", citation: "Doe JA" }
function splitName(full) {
  const parts = full.trim().split(/\s+/);
  const family = parts.length > 1 ? parts.pop() : parts[0];
  const given = parts.length ? parts.join(" ") : "";
  const initials = given.split(/[\s.-]+/).filter(Boolean).map((p) => p[0].toUpperCase()).join("");
  return { given, family, citation: initials ? `${family} ${initials}` : family };
}

if (token) {
  const known = new Set(people.map((p) => p.github?.toLowerCase()));
  const contributors = await gh(`repos/${repo}/contributors?per_page=100`);
  for (const c of contributors) {
    if (c.type !== "User" || c.login.endsWith("[bot]") || known.has(c.login.toLowerCase())) continue;
    const user = await gh(`users/${c.login}`);
    const n = splitName(user.name || c.login);
    people.push({ citation_name: n.citation, given_names: n.given, family_names: n.family, github: c.login, role: "Contributor" });
    console.log(`Added contributor ${c.login} as "${n.citation}"`);
  }
  writeFileSync(file, JSON.stringify(people, null, 2) + "\n");
}

const q = (s) => JSON.stringify(s);
const cff = [
  "# Generated by scripts/update-contributors.mjs from contributors.json. Do not edit by hand.",
  "cff-version: 1.2.0",
  'message: "If you found a database through this catalogue, please acknowledge it as below."',
  'title: "Open Health Databases: a catalogue of freely available health datasets"',
  "type: dataset",
  "authors:",
  ...people.flatMap((p) => [
    `  - family-names: ${q(p.family_names)}`,
    ...(p.given_names ? [`    given-names: ${q(p.given_names)}`] : []),
    ...(p.github ? [`    alias: ${q(p.github)}`] : []),
  ]),
  'url: "https://open-health-databases.vercel.app"',
  'repository-code: "https://github.com/abdullahdmc/open-health-databases"',
  'license: "CC-BY-4.0"',
  "keywords:",
  '  - "open data"',
  '  - "health databases"',
  '  - "clinical datasets"',
  "",
].join("\n");
writeFileSync(join(root, "CITATION.cff"), cff);
console.log(`${people.length} contributor(s); CITATION.cff written`);
